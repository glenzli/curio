// Restricted, generated teaching fixture. This is not a general TIFF/DNG decoder.
export const width = 32,
  height = 32,
  black = 64,
  white = 4095;
export const samples = Array.from({ length: width * height }, (_, i) =>
  i < 4
    ? [32, 64, 4095, 4000][i]
    : 64 + (((i % width) * 113 + Math.floor(i / width) * 197) % 3800),
);
const types = { 1: 1, 2: 1, 3: 2, 4: 4, 5: 8, 10: 8 };
const ascii = (s) => Array.from(new TextEncoder().encode(s + "\0"));
export function createDng() {
  const tags = [
    [254, 4, [0]],
    [256, 4, [width]],
    [257, 4, [height]],
    [258, 3, [16]],
    [259, 3, [1]],
    [262, 3, [32803]],
    [
      270,
      2,
      ascii(
        "Synthetic linear CFA; generated by Curio; same license as the book; not a measured camera profile",
      ),
    ],
    [271, 2, ascii("Markdown Book")],
    [272, 2, ascii("Teaching CFA 32x32")],
    [273, 4, [0]],
    [274, 3, [1]],
    [277, 3, [1]],
    [278, 4, [height]],
    [279, 4, [samples.length * 2]],
    [284, 3, [1]],
    [33421, 3, [2, 2]],
    [33422, 1, [0, 1, 1, 2]],
    [50706, 1, [1, 4, 0, 0]],
    [50707, 1, [1, 1, 0, 0]],
    [50708, 2, ascii("Curio synthetic teaching CFA")],
    [50710, 1, [0, 1, 2]],
    [50711, 3, [1]],
    [50713, 3, [1, 1]],
    [50714, 5, [[black, 1]]],
    [50717, 4, [white]],
    [
      50718,
      5,
      [
        [1, 1],
        [1, 1],
      ],
    ],
    [50719, 4, [0, 0]],
    [50720, 4, [width, height]],
    [50721, 10, Array.from({ length: 9 }, (_, i) => [i % 4 === 0 ? 1 : 0, 1])],
    [
      50728,
      5,
      [
        [1, 1],
        [1, 1],
        [1, 1],
      ],
    ],
    [50778, 3, [21]],
    [50829, 4, [0, 0, height, width]],
  ].sort((a, b) => a[0] - b[0]);
  let offset = 8 + 2 + tags.length * 12 + 4;
  const records = tags.map(([tag, type, values]) => {
    const bytes = types[type] * values.length,
      position = bytes > 4 ? offset : null;
    if (position !== null) offset += bytes + (bytes % 2);
    return { tag, type, values, position };
  });
  records.find((r) => r.tag === 273).values = [offset];
  const array = new Uint8Array(offset + samples.length * 2),
    view = new DataView(array.buffer);
  array.set([73, 73, 42, 0, 8, 0, 0, 0]);
  view.setUint16(8, records.length, true);
  records.forEach((r, i) => {
    const entry = 10 + i * 12;
    view.setUint16(entry, r.tag, true);
    view.setUint16(entry + 2, r.type, true);
    view.setUint32(entry + 4, r.values.length, true);
    if (r.position !== null) view.setUint32(entry + 8, r.position, true);
    const start = r.position ?? entry + 8;
    r.values.forEach((v, j) => {
      const pos = start + j * types[r.type];
      if (r.type === 1 || r.type === 2) view.setUint8(pos, v);
      else if (r.type === 3) view.setUint16(pos, v, true);
      else if (r.type === 4) view.setUint32(pos, v, true);
      else {
        const set = r.type === 10 ? "setInt32" : "setUint32";
        view[set](pos, v[0], true);
        view[set](pos + 4, v[1], true);
      }
    });
  });
  samples.forEach((x, i) => view.setUint16(offset + 2 * i, x, true));
  return array;
}
export function inspectDng(
  bytes,
  { wrongEndian = false, blackOverride = null } = {},
) {
  if (!(bytes instanceof Uint8Array) || bytes.byteLength < 16)
    throw RangeError("Truncated TIFF");
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength),
    little = bytes[0] === 73 && bytes[1] === 73;
  if (
    !little ||
    view.getUint16(2, true) !== 42 ||
    view.getUint32(4, true) !== 8
  )
    throw RangeError("Only the local little-endian fixture is supported");
  const count = view.getUint16(8, true);
  if (count > 64 || 10 + 12 * count + 4 > bytes.length)
    throw RangeError("Invalid local IFD");
  const tags = [];
  for (let i = 0; i < count; i++) {
    const entry = 10 + 12 * i,
      tag = view.getUint16(entry, true),
      type = view.getUint16(entry + 2, true),
      n = view.getUint32(entry + 4, true),
      size = types[type];
    if (!size || n > 4096) throw RangeError("Unsupported local tag");
    const start = n * size > 4 ? view.getUint32(entry + 8, true) : entry + 8;
    if (start + n * size > bytes.length) throw RangeError("Tag outside file");
    const values = Array.from({ length: n }, (_, j) => {
      const p = start + j * size;
      if (type === 1 || type === 2) return view.getUint8(p);
      if (type === 3) return view.getUint16(p, true);
      if (type === 4) return view.getUint32(p, true);
      return (
        view[type === 10 ? "getInt32" : "getUint32"](p, true) /
        view.getUint32(p + 4, true)
      );
    });
    tags.push({ tag, type, count: n, start, values });
  }
  const get = (id) => tags.find((t) => t.tag === id)?.values;
  if (
    get(256)?.[0] !== width ||
    get(257)?.[0] !== height ||
    get(258)?.[0] !== 16 ||
    get(259)?.[0] !== 1 ||
    get(262)?.[0] !== 32803 ||
    get(277)?.[0] !== 1 ||
    get(278)?.[0] !== height ||
    get(279)?.[0] !== samples.length * 2
  )
    throw RangeError("Not the supported single-strip CFA fixture");
  const offset = get(273)?.[0];
  if (!Number.isInteger(offset) || offset + samples.length * 2 > bytes.length)
    throw RangeError("Truncated sample strip");
  const decoded = Array.from({ length: samples.length }, (_, i) =>
    view.getUint16(offset + 2 * i, !wrongEndian),
  );
  const level = blackOverride ?? get(50714)[0],
    top = get(50717)[0];
  if (!Number.isFinite(level) || top <= level)
    throw RangeError("Invalid normalization");
  return {
    tags,
    decoded,
    offset,
    black: level,
    white: top,
    cfa: get(33422),
    normalized: decoded.map((x) => (x - level) / (top - level)),
    mismatches: decoded.filter((x, i) => x !== samples[i]).length,
  };
}
